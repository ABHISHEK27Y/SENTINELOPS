// Generates local demo workloads; configuration comes from root Kustomize maps.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const workloads = [
  {
    name: 'prometheus',
    image: 'prom/prometheus:v2.55.0',
    ports: [9090],
    args: [
      '--config.file=/etc/prometheus/prometheus.yml',
      '--storage.tsdb.path=/prometheus',
      '--storage.tsdb.retention.time=6h',
    ],
    ready: '/-/ready',
    data: '/prometheus',
    maps: [
      ['prometheus-config', '/etc/prometheus'],
      ['prometheus-alerts', '/etc/prometheus/alerts'],
    ],
  },
  {
    name: 'loki',
    image: 'grafana/loki:3.1.0',
    ports: [3100],
    args: ['-config.file=/etc/loki/config.yaml'],
    ready: '/ready',
    data: '/loki',
    maps: [['loki-config', '/etc/loki']],
  },
  {
    name: 'alertmanager',
    image: 'prom/alertmanager:v0.27.0',
    ports: [9093],
    args: ['--config.file=/etc/alertmanager/alertmanager.yml', '--storage.path=/alertmanager'],
    ready: '/-/ready',
    data: '/alertmanager',
    maps: [['alertmanager-config', '/etc/alertmanager']],
  },
  {
    name: 'jaeger',
    image: 'jaegertracing/all-in-one:1.62.0',
    ports: [16686, 4317, 4318],
    env: [{ name: 'COLLECTOR_OTLP_ENABLED', value: 'true' }],
    maps: [],
  },
  {
    name: 'otel-collector',
    image: 'otel/opentelemetry-collector-contrib:0.111.0',
    ports: [4317, 4318, 8889],
    args: ['--config=/etc/otel/config.yaml'],
    maps: [['otel-config', '/etc/otel']],
  },
  {
    name: 'grafana',
    image: 'grafana/grafana:11.3.0',
    ports: [3000],
    ready: '/api/health',
    data: '/var/lib/grafana',
    env: [{ name: 'GF_AUTH_ANONYMOUS_ENABLED', value: 'false' }],
    maps: [
      ['grafana-datasources', '/etc/grafana/provisioning/datasources'],
      ['grafana-providers', '/etc/grafana/provisioning/dashboards'],
      ['grafana-dashboards', '/var/lib/grafana/dashboards'],
    ],
  },
];
const resources = [];
for (const w of workloads) {
  const metadata = { name: w.name, namespace: 'sentinelops' };
  if (w.data)
    resources.push({
      apiVersion: 'v1',
      kind: 'PersistentVolumeClaim',
      metadata: { ...metadata, name: `${w.name}-data` },
      spec: { accessModes: ['ReadWriteOnce'], resources: { requests: { storage: '2Gi' } } },
    });
  const volumes = w.maps.map(([name]) => ({ name, configMap: { name } }));
  const mounts = w.maps.map(([name, mountPath]) => ({ name, mountPath, readOnly: true }));
  if (w.data) {
    volumes.push({ name: 'data', persistentVolumeClaim: { claimName: `${w.name}-data` } });
    mounts.unshift({ name: 'data', mountPath: w.data });
  }
  resources.push({
    apiVersion: 'apps/v1',
    kind: 'Deployment',
    metadata,
    spec: {
      replicas: 1,
      strategy: { type: 'Recreate' },
      selector: { matchLabels: { app: w.name } },
      template: {
        metadata: { labels: { app: w.name } },
        spec: {
          ...(w.data ? { securityContext: { fsGroup: w.name === 'grafana' ? 472 : 10001 } } : {}),
          containers: [
            {
              name: w.name,
              image: w.image,
              args: w.args,
              env: w.env,
              ports: w.ports.map(containerPort => ({ containerPort })),
              volumeMounts: mounts,
              readinessProbe: w.ready
                ? {
                    httpGet: { path: w.ready, port: w.ports[0] },
                    initialDelaySeconds: 10,
                    periodSeconds: 10,
                  }
                : {
                    tcpSocket: { port: w.name === 'otel-collector' ? 4318 : 16686 },
                    initialDelaySeconds: 10,
                  },
              resources: {
                requests: { cpu: '100m', memory: '128Mi' },
                limits: { cpu: '1', memory: '512Mi' },
              },
            },
          ],
          volumes,
        },
      },
    },
  });
  resources.push({
    apiVersion: 'v1',
    kind: 'Service',
    metadata,
    spec: {
      selector: { app: w.name },
      ports: w.ports.map(port => ({ name: `port-${port}`, port, targetPort: port })),
    },
  });
}
fs.writeFileSync(
  path.join(scriptDirectory, '../infrastructure/kubernetes/06-monitoring.yaml'),
  '# Generated by scripts/generate-monitoring.mjs. Local demo; Jaeger traces are ephemeral.\n' +
    resources.map(r => JSON.stringify(r, null, 2)).join('\n---\n') +
    '\n'
);
